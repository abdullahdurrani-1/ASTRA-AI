"""Write docs/URDU_QA.md: every Urdu / Roman Urdu string Astra can show, for native review.

Usage: python -m devtools.export_urdu_qa
"""

from pathlib import Path

import yaml

from app.services.language import GENERATION_ERROR, INSUFFICIENT_EVIDENCE

ROOT = Path(__file__).resolve().parents[2]
REPLIES = ROOT / "backend" / "app" / "data" / "conversation" / "replies.yaml"
OUT = ROOT / "docs" / "URDU_QA.md"


def _walk(node, path, out):
    if isinstance(node, dict):
        for key, value in node.items():
            _walk(value, [*path, str(key)], out)
    elif isinstance(node, list):
        for i, value in enumerate(node, 1):
            _walk(value, [*path, str(i)], out)
    else:
        out.append((path, str(node)))


def main() -> None:
    data = yaml.safe_load(REPLIES.read_text(encoding="utf-8"))
    rows: dict[str, list[tuple[str, str]]] = {"ur": [], "roman_ur": []}
    flat: list[tuple[list[str], str]] = []
    _walk(data, [], flat)
    for path, text in flat:
        lang = next((p for p in path if p in rows), None)
        if lang:
            rows[lang].append((".".join(p for p in path if p != lang), text))
    rows["ur"] += [
        ("refusal.insufficient_evidence", INSUFFICIENT_EVIDENCE["ur"]),
        ("error.generation", GENERATION_ERROR["ur"]),
    ]

    lines = [
        "# Urdu string review (native speaker QA)",
        "",
        "Generated by `python -m devtools.export_urdu_qa` from "
        "`backend/app/data/conversation/replies.yaml` and `app/services/language.py`. "
        "Do not edit this file by hand: fix the source, then regenerate.",
        "",
        "For each row, mark **OK** or write a correction. Check: natural register (آپ form), "
        "correct greeting etiquette, spelling, no literal-translation feel.",
        "",
    ]
    for lang, title in (("ur", "Urdu script"), ("roman_ur", "Roman Urdu")):
        lines += [f"## {title} ({len(rows[lang])} strings)", "", "| Key | Text | Review |",
                  "|---|---|---|"]  # fmt: skip
        for key, text in rows[lang]:
            cell = text.replace("|", r"\|").replace("\n", " ")
            shown = f'<span dir="rtl">{cell}</span>' if lang == "ur" else cell
            lines.append(f"| `{key}` | {shown} | |")
        lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT} ({sum(len(v) for v in rows.values())} strings)")


if __name__ == "__main__":
    main()
